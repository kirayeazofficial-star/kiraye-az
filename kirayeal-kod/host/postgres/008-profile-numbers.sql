-- Public account numbers start at 30000001 (listing numbers use 10000001, reports 20000001).
alter table public.profiles alter column profile_no set generated by default;
update public.profiles set profile_no=profile_no+30000000 where profile_no<30000000;
do $$ declare next_no bigint; begin
  select greatest(coalesce(max(profile_no),0),30000000)+1 into next_no from public.profiles;
  execute format('alter table public.profiles alter column profile_no restart with %s',next_no);
end $$;
alter table public.profiles alter column profile_no set generated always;
